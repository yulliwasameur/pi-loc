"""Tie the manuscript to the results.

1. `macros`: write paper/numbers.tex, one LaTeX macro per reported number,
   computed from results/summary.json. The manuscript uses only these macros
   for results, so no result is ever typed by hand.
2. `check`: fail if the manuscript contains a decimal number that is not a
   design constant (thresholds, k values, sizes) listed below.
"""
import json, re, sys

DET = {"protectai-deberta-v2": "Pa", "deepset-deberta": "Ds", "fmops-distilbert": "Fm"}
EXP = {"occlusion": "Occ", "kernelshap": "Shap", "gradxinput": "Grad", "attention": "Attn"}
# numbers that describe the design, not a result
ALLOWED = {"0.5", "0.05", "0.144", "0.95", "1.0", "1.25", "0.98", "3.1", "3.6", "0.9", "1.2", "10.1109", "0.000"}


def f3(x):
    s = f"{x:.3f}"
    return "0.000" if s == "-0.000" else s


def pct(x, nd=1):
    return f"{100 * x:.{nd}f}"


def macros(summary_path, out_path):
    S = json.load(open(summary_path))
    m = {}
    b = S["build"]
    m["NPos"] = f"{b['distinct_positive_payloads']:,}".replace(",", "{,}")
    m["NHnPool"] = str(b["benign_trigger_sentences_available"])
    m["NCaught"] = str(S["matched"]["caught_by_anchor"])
    for d, a in DET.items():
        D = S["detection"][d]
        m[f"{a}Auc"] = f3(D["roc_auc"]); m[f"{a}Tpr"] = f3(D["tpr_inj"])
        m[f"{a}FprHn"] = f3(D["fpr_hn"]); m[f"{a}FprCl"] = f3(D["fpr_clean"])
        m[f"{a}TprCal"] = f3(D["tpr_at_fpr05"]); m[f"{a}TprPct"] = pct(D["tpr_inj"])
        m[f"{a}TprCalPct"] = pct(D["tpr_at_fpr05"], 0); m[f"{a}MissCalPct"] = pct(1 - D["tpr_at_fpr05"], 0)
        m[f"{a}TprWiki"] = pct(D["by_family"]["wiki"]); m[f"{a}TprEmail"] = pct(D["by_family"]["email"])
        E = S["explain"][d]
        m[f"{a}Chance"] = f3(E["chance_auprc"])
        for e, x in EXP.items():
            R = E[e]
            m[f"{a}{x}Au"] = f3(R["auprc"]); m[f"{a}{x}AuLo"] = f3(R["auprc_ci"][0]); m[f"{a}{x}AuHi"] = f3(R["auprc_ci"][1])
            m[f"{a}{x}Ps"] = f3(R["p_at_span"]); m[f"{a}{x}Pg"] = f3(R["pointing"])
            m[f"{a}{x}PgLo"] = f3(R["pointing_ci"][0]); m[f"{a}{x}PgHi"] = f3(R["pointing_ci"][1])
            m[f"{a}{x}PgPct"] = pct(R["pointing"])
            m[f"{a}{x}Co"] = f3(R["comprehensiveness"]); m[f"{a}{x}CoLo"] = f3(R["comprehensiveness_ci"][0])
            m[f"{a}{x}CoHi"] = f3(R["comprehensiveness_ci"][1]); m[f"{a}{x}Re"] = f3(R["retained"])
    for key, v in S["tests"].items():
        for pair, r in v.items():
            a, _, c = pair.partition("_vs_")
            name = f"P{key.capitalize()[:2]}{EXP[a]}{EXP[c]}"
            p = r["p"]
            m[name] = "<10^{-5}" if p < 1e-5 else (f"={p:.1e}".replace("e-0", "\\times10^{-").replace("e-", "\\times10^{-") + "}" if p < 0.001 else f"={p:.3f}")
    for key, r in S["sanitization"].items():
        e, k = key.split("@")
        n = f"San{EXP[e]}{ {'10': 'Ten', '20': 'Twenty'}[k] }"
        m[n + "Pb"] = f3(r["p_before"]); m[n + "Pa"] = f3(r["p_after"]); m[n + "Dr"] = f3(r["drop"])
        m[n + "Sp"] = f3(r["span_removed"]); m[n + "Co"] = f3(r["collateral"])
        m[n + "SpPct"] = pct(r["span_removed"]); m[n + "CoPct"] = pct(r["collateral"])
    with open(out_path, "w") as f:
        f.write("% Generated by piloc/check_paper.py from results/summary.json. Do not edit.\n")
        for k, v in sorted(m.items()):
            assert re.fullmatch(r"[A-Za-z]+", k), k
            f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
    return m


def check(tex_path):
    t = open(tex_path).read()
    t = re.sub(r"(?m)%.*$", "", t)
    body = t.split("\\begin{document}", 1)[1]
    body = re.sub(r"\\(cite|ref|label|includegraphics|url|doi|history)\{[^}]*\}", "", body)
    bad = sorted({x for x in re.findall(r"(?<![\w.])\d+\.\d+", body) if x not in ALLOWED})
    if bad:
        print("Hard-coded decimals found in the manuscript:", bad)
        sys.exit(1)
    print("OK: every result in the manuscript comes from numbers.tex")


if __name__ == "__main__":
    if sys.argv[1] == "macros":
        macros(sys.argv[2], sys.argv[3])
    else:
        check(sys.argv[1])
